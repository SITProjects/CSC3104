#!/usr/bin/env bash
set -euo pipefail
umask 077

# Usage:
# sudo bash infra/join-worker.sh \
#   <node-name> <wg-config> <token-file> <k3s-version>

die() {
    echo "Error: $*" >&2
    exit 1
}

[[ $EUID -eq 0 ]] || die "Run with sudo."
[[ $# -eq 3 ]] ||
    die "Usage: $0 <node-name> <wg-config> <token-file>"

NAME="$1"
WG_CONFIG="$2"
TOKEN_FILE="$3"
VERSION="v1.34.1+k3s1"

[[ "$NAME" =~ ^[a-z0-9]([a-z0-9-]*[a-z0-9])?$ &&
   ${#NAME} -le 63 ]] || die "Use a valid lowercase node name."

[[ -s "$WG_CONFIG" ]] || die "WireGuard configuration is missing."
[[ -s "$TOKEN_FILE" ]] || die "K3s join token is missing."

# Read the address from the configuration generated by add-peer.sh.
CIDR="$(awk -F '=' '
    /^[[:space:]]*Address[[:space:]]*=/ {
        gsub(/[[:space:]]/, "", $2)
        print $2
    }
' "$WG_CONFIG")"

[[ "$CIDR" =~ ^10\.10\.0\.([0-9]{3})/24$ ]] ||
    die "Expected a worker address in 10.10.0.0/24."

OCTET="${BASH_REMATCH[1]}"
IP="${CIDR%/*}"

# Campus workers: .100-.199
# Burst workers: .200-.204, with matching slot names
(( OCTET >= 100 && OCTET <= 204 )) ||
    die "Address is outside the worker ranges."

if (( OCTET >= 200 )); then
    [[ "$NAME" == "slot-$OCTET" ]] ||
        die "Burst worker $IP must be named slot-$OCTET."
elif [[ "$NAME" == slot-* ]]; then
    die "slot- names are reserved for burst workers."
fi

# Install and configure WireGuard.
apt-get update
DEBIAN_FRONTEND=noninteractive apt-get install -y \
    wireguard curl ca-certificates iputils-ping

install -d -m 700 /etc/wireguard
install -m 600 "$WG_CONFIG" /etc/wireguard/wg0.conf

systemctl enable wg-quick@wg0
systemctl restart wg-quick@wg0

# Confirm that the hub is reachable over the VPN.
ping -I wg0 -c 3 -W 3 10.10.0.1 >/dev/null ||
    die "Cannot reach the WireGuard hub."

# Store the join token for the K3s agent service.
install -d -m 700 /etc/rancher/k3s
install -m 600 "$TOKEN_FILE" /etc/rancher/k3s/agent-token

# Make the agent wait for WireGuard during startup.
install -d -m 755 /etc/systemd/system/k3s-agent.service.d

cat > /etc/systemd/system/k3s-agent.service.d/wireguard.conf <<'EOF'
[Unit]
Requires=wg-quick@wg0.service
After=wg-quick@wg0.service
EOF

systemctl daemon-reload

# Give pods 30 s to checkpoint on PC shutdown. Must be a config drop-in:
# as a --kubelet-arg it stops the kubelet starting.
install -d -m 755 /var/lib/rancher/k3s/agent/etc/kubelet.conf.d

cat > /var/lib/rancher/k3s/agent/etc/kubelet.conf.d/50-graceful-shutdown.conf <<'EOF'
apiVersion: kubelet.config.k8s.io/v1beta1
kind: KubeletConfiguration
shutdownGracePeriod: 30s
shutdownGracePeriodCriticalPods: 0s
EOF

# Download the installer, then install the matching K3s version.
INSTALLER="$(mktemp)"
trap 'rm -f -- "$INSTALLER"' EXIT

curl --fail --silent --show-error --location \
    https://get.k3s.io -o "$INSTALLER"

INSTALL_K3S_VERSION="$VERSION" sh "$INSTALLER" agent \
    --server https://10.10.0.1:6443 \
    --token-file /etc/rancher/k3s/agent-token \
    --node-name "$NAME" \
    --node-ip "$IP" \
    --flannel-iface wg0 \
    --node-label idlecloud/role=worker
